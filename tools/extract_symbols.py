"""Dev tool (not part of the build): extract symbol data from MathLive.

Usage: python3 -I tools/extract_symbols.py <commands.html> <mathlive.mjs> <out_dir>

Inputs are untrusted downloads and are only read as text; nothing is executed.
"""
import html
import re
import sys

# Preferred canonical commands where MathLive's UNICODE_TO_LATEX table (or the
# first-pair order) disagrees with the project's canonical form.
PREFERRED = {
    0x2264: "\\leq",
    0x2265: "\\geq",
    0x2192: "\\rightarrow",
    0x2260: "\\ne",
}

# Greek capitals that MathLive only defines as macros (\Alpha ...), not pairs.
GREEK_CAPS = {
    "\\Alpha": 0x391, "\\Beta": 0x392, "\\Epsilon": 0x395, "\\Zeta": 0x396,
    "\\Eta": 0x397, "\\Iota": 0x399, "\\Kappa": 0x39A, "\\Mu": 0x39C,
    "\\Nu": 0x39D, "\\Omicron": 0x39F, "\\Rho": 0x3A1, "\\Tau": 0x3A4,
    "\\Chi": 0x3A7,
}


def main(html_path, mjs_path, out_dir):
    with open(html_path, encoding="utf-8", errors="replace") as f:
        raw = f.read()
    # Convert HTML to text: block/line boundaries become newlines, inline
    # tags are dropped, so a code line `<div class="line">\\ne<br></div>` is
    # the text line `\\ne` while `\\frac{a}{b}` stays one longer line.
    text = re.sub(r"<br\s*/?>|</div>|</p>|</li>|</h\d>|</tr>", "\n", raw)
    text = re.sub(r"<[^>]+>", "", text)
    text = html.unescape(text)
    cmds = []
    seen = set()
    for line in text.splitlines():
        line = line.strip()
        if re.fullmatch(r"\\[A-Za-z]+", line) and line not in seen:
            seen.add(line)
            cmds.append(line)
    with open(f"{out_dir}/mathlive-commands.txt", "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(cmds) + "\n")

    with open(mjs_path, encoding="utf-8", errors="replace") as f:
        src = f.read()
    pairs = []
    done = set()
    for m in re.finditer(r'\[\s*"(\\\\[A-Za-z]+)"\s*,\s*(\d+)', src):
        cmd = m.group(1).replace("\\\\", "\\")
        if cmd not in done:
            done.add(cmd)
            pairs.append((cmd, int(m.group(2))))
    canon = {}
    for m in re.finditer(r'^\s*(\d+): "(\\\\[A-Za-z]+)"', src, re.M):
        canon.setdefault(int(m.group(1)), m.group(2).replace("\\\\", "\\"))
    for cmd, cp in GREEK_CAPS.items():
        if cmd not in done:
            done.add(cmd)
            pairs.append((cmd, cp))
    canon.update(PREFERRED)

    # For each codepoint the canonical command goes first, then the other
    # commands in file order. A canonical command without a pair of its own
    # (e.g. \\ne) is added when it is documented or in PREFERRED.
    documented = set(cmds)
    by_cp = {}
    for cmd, cp in pairs:
        by_cp.setdefault(cp, []).append(cmd)
    for cp, c in canon.items():
        if c in documented or c in PREFERRED.values():
            lst = by_cp.setdefault(cp, [])
            if c in lst:
                lst.remove(c)
            lst.insert(0, c)
    result = [(c, cp) for cp, lst in by_cp.items() for c in lst]
    with open(f"{out_dir}/symbols.csv", "w", encoding="utf-8", newline="\n") as f:
        f.write("# command,codepoint_hex (generated by tools/extract_symbols.py; MathLive, MIT)\n")
        for cmd, cp in result:
            f.write(f"{cmd},{cp:04X}\n")
    print(f"commands={len(cmds)} symbols={len(result)}")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
